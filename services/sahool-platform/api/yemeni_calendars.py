# ═══════════════════════════════════════════════════════════════════
# ٤. الجسر الزمني: تاريخ → المنزلة/المعلم النشط → السياق التراثي
#    (يسدّ الفجوة: ربط تلقائي بدل تمرير النجم يدويّاً)
# ═══════════════════════════════════════════════════════════════════
def _md_to_doy(month: int, day: int, year: int = 2025) -> int:
    """يحوّل (شهر, يوم) لرقم اليوم في السنة (مرجع غير كبيسة للاستقرار)."""
    try:
        return date(year, month, day).timetuple().tm_yday
    except ValueError:
        return 1


def active_mansion_for_date(target: date) -> LunarMansion | None:
    """يُرجِع المنزلة القمريّة النشطة في تاريخ معيّن (الجسر الزمني).

    صدق: التواريخ تقريبيّة؛ النتيجة استرشاديّة لا قطعيّة. عند الحدود قد
    تتداخل منزلتان — نُرجِع الأقرب بدايةً قبل التاريخ.
    """
    doy = target.timetuple().tm_yday
    # نبني نقاط البداية بترتيب دائري، ونجد المنزلة التي يقع doy ضمن مدّتها
    best: LunarMansion | None = None
    best_gap = 999
    for m in LUNAR_MANSIONS:
        start_doy = _md_to_doy(*m.approx_start_md)
        # المسافة الدائريّة من البداية للتاريخ (ضمن المدّة؟)
        gap = (doy - start_doy) % 365
        if gap < m.duration_days and gap < best_gap:
            best, best_gap = m, gap
    # fallback: لو لم تطابق (فجوة تقريب)، أقرب بداية سابقة
    if best is None:
        for m in LUNAR_MANSIONS:
            start_doy = _md_to_doy(*m.approx_start_md)
            gap = (doy - start_doy) % 365
            if gap < best_gap:
                best, best_gap = m, gap
    return best


def himyarite_month_for_date(target: date) -> HimyariteMonth | None:
    """يُرجِع الشهر الحميري التقريبي (المقابلة الميلاديّة الأوسع تداولاً).

    صدق: المقابلة تختلف بين المصادر؛ هذه رواية «ذو الثابة=أبريل». تقريبيّة.
    """
    # الشهر الحميري ≈ يبدأ منتصف الشهر الميلادي السابق لمقابلته. تبسيط:
    # نربط بترتيب: ذو الثابة(أبريل=4) ... دورة 12 شهراً من أبريل.
    idx = (target.month - 4) % 12  # أبريل=0 (ذو الثابة)
    return HIMYARITE_MONTHS[idx] if 0 <= idx < len(HIMYARITE_MONTHS) else None


def calendar_context_for_date(target_iso: str, governorate: str | None = None) -> dict:
    """الجسر الكامل: تاريخ → منزلة نشطة + شهر حميري + ملف المنطقة.

    صدق: طبقة عرض ومعرفة فقط؛ لا تدخل القرار. التواريخ تقريبيّة (±أيّام).
    التباين بين المصادر مُعلَن. التوقيت الدقيق يبقى على GDD/الفيزياء.
    """
    try:
        y, m, d = map(int, target_iso.split("-"))
        target = date(y, m, d)
    except (ValueError, AttributeError):
        return {"error_ar": "تاريخ غير صالح (استخدم YYYY-MM-DD)"}

    mansion = active_mansion_for_date(target)
    himyari = himyarite_month_for_date(target)
    region = None
    if governorate:
        for p in REGIONAL_PROFILES:
            if governorate in p.governorates_ar:
                region = p
                break

    return {
        "display_only": True,
        "used_in_decision_engine": False,
        "date_iso": target_iso,
        "active_mansion": mansion.to_dict() if mansion else None,
        "himyarite_month": himyari.to_dict() if himyari else None,
        "regional_profile": region.to_dict() if region else None,
        "disclaimer_ar": (
            "سياق تقويمي تراثي (عرض ومعرفة فقط). التواريخ تقريبيّة (±أيّام) "
            "والمقابلات تختلف بين المصادر. التوقيت والكميّات الفعليّة تُبنى على "
            "القياس الفيزيائي (GDD، ميزان الماء، التربة) لا على التقويم النجمي."
        ),
        "marker_for_proverbs": mansion.name_ar if mansion else None,  # جسر للأمثال
    }


