# مرادفات المناطق → للمطابقة الإقليميّة
_REGION_KEYS = {
    "al_jawf": ["الجوف", "برط"],
    "taiz": ["تعز", "صبر", "الحجريّة"],
    "raymah": ["ريمة", "الضبيبي"],
    "al_bayda": ["الهضبة"],
    "sanaa": ["الهضبة"],
    "dhamar": ["الهضبة"],
    "ibb": ["الهضبة"],
}


def get_proverbs(
    marker: str | None = None,
    governorate: str | None = None,
) -> dict:
    """يُرجع أمثالاً زراعيّة موثّقة، اختياريّاً مفلترة بالمعلم/النجم والمنطقة.

    Args:
        marker: المعلم/النجم (سهيل، الروابع، علان، علب...).
        governorate: المحافظة لترشيح الأمثال الإقليميّة + العامّة.
    """
    items = _PROVERBS

    if marker:
        items = [p for p in items if marker in p.marker_ar]

    if governorate:
        region_terms = _REGION_KEYS.get(governorate, [])
        # نعرض: العامّ دائماً + الإقليمي المطابق للمحافظة
        items = [
            p
            for p in items
            if "عامّ" in p.region_ar or any(term in p.region_ar for term in region_terms)
        ]

    return {
        "display_only": True,
        "used_in_decision_engine": False,
        "purpose_ar": "حِكَم زراعيّة تراثيّة تجسر الثقة — تُعرَض بجانب التوصية العلميّة",
        "disclaimer_ar": (
            "أمثال زراعيّة تراثيّة تُعرَض كسياق ثقافي مألوف للمزارع، وهي **لا تدخل** "
            "في حساب أيّ توصية. التوقيت والكميّات تُبنى على القياس الفيزيائي (GDD، "
            "ميزان الماء، التربة)."
        ),
        "count": len(items),
        "proverbs": [p.to_dict() for p in items],
        "academic_references_ar": _ACADEMIC_REFS,
    }
