def niche_crop_detail(crop_ar: str) -> Dict:
    """تفصيل منتج متخصّص محدّد."""
    kw = crop_ar.strip()
    for name, info in _NICHE_CROPS.items():
        if kw in name or name in kw:
            return {"supported": True, "name_ar": name, **info}
    return {
        "supported": False,
        "message_ar": f"لا تفصيل لـ«{crop_ar}». المتاح: " + "، ".join(_NICHE_CROPS),
    }
