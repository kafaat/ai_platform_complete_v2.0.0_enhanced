from __future__ import annotations

# معامل الجريان حسب نوع السطح (كسر المطر الذي يُحصد فعليّاً)
_RUNOFF_COEFF = {
    "roof": 0.85,  # سطح صلب (مبنى) — كفاءة عالية
    "compacted": 0.55,  # أرض مدكوكة/ممهّدة لحصاد السيول
    "natural": 0.30,  # أرض طبيعيّة (تسرّب أعلى)
    "terrace": 0.45,  # مدرّجات (تحجز جزءاً وتسرّب جزءاً للتربة)
}


def harvest_potential(
    catchment_area_m2: float, annual_rain_mm: float, surface: str = "roof"
) -> dict:
    """يقدّر كميّة مياه الأمطار القابلة للحصاد سنويّاً.

    الحجم (لتر) = المساحة (م²) × المطر (مم) × معامل الجريان
    (1 مم مطر على 1 م² = 1 لتر)
    """
    if catchment_area_m2 <= 0 or annual_rain_mm < 0:
        return {"supported": False, "message_ar": "أدخل مساحة ومطراً صحيحين."}
    coeff = _RUNOFF_COEFF.get(surface.strip().lower(), _RUNOFF_COEFF["roof"])
    liters = catchment_area_m2 * annual_rain_mm * coeff
    m3 = liters / 1000
    return {
        "supported": True,
        "catchment_area_m2": catchment_area_m2,
        "annual_rain_mm": annual_rain_mm,
        "surface": surface,
        "runoff_coefficient": coeff,
        "harvestable_liters": round(liters),
        "harvestable_m3": round(m3, 1),
        "advice_ar": (
            f"يمكن حصاد ~{round(m3, 1)} م³ ({round(liters)} لتر) سنويّاً من سطح "
            f"{catchment_area_m2:.0f} م² بمطر {annual_rain_mm:.0f} مم. خزّنها لريّ "
            "تكميلي في فترات الجفاف."
        ),
        "note_ar": (
            "تقدير إرشادي — الكميّة الفعليّة تقلّ بالتبخّر والتسرّب. كلّما صلب السطح زاد الجريان المحصود."
        ),
    }


