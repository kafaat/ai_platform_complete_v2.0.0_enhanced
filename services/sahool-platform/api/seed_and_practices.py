def evaluate_seed_source(certified: bool, purity_pct: Optional[float] = None,
                         germination_pct: Optional[float] = None) -> Dict:
    """يقيّم جودة مصدر بذار بناءً على الاعتماد والنقاوة والإنبات."""
    flags: List[str] = []
    ok = True

    if not certified:
        flags.append("⚠ البذار غير معتمد — خطر أمراض أو عدم مطابقة الصنف. يُفضّل المعتمد.")
        ok = False
    else:
        flags.append("✓ بذار معتمد — صفات الصنف مضمونة نسبيّاً.")

    if purity_pct is not None:
        if purity_pct >= 98:
            flags.append(f"✓ نقاوة صنفيّة ممتازة ({purity_pct:.0f}%).")
        elif purity_pct >= 95:
            flags.append(f"نقاوة مقبولة ({purity_pct:.0f}%) — المعتمد عادةً ≥98%.")
        else:
            flags.append(f"⚠ نقاوة منخفضة ({purity_pct:.0f}%) — قد تختلط أصناف.")
            ok = False

    if germination_pct is not None:
        if germination_pct >= 85:
            flags.append(f"✓ إنبات جيّد ({germination_pct:.0f}%).")
        elif germination_pct >= 70:
            flags.append(f"إنبات متوسّط ({germination_pct:.0f}%) — زد معدّل البذار للتعويض.")
        else:
            flags.append(f"⚠ إنبات ضعيف ({germination_pct:.0f}%) — كثافة نباتيّة ناقصة محتملة.")
            ok = False

    return {
        "acceptable": ok,
        "summary_ar": "مصدر بذار جيّد." if ok else "راجع مصدر البذار قبل الاعتماد عليه.",
        "flags_ar": flags,
        "disclaimer_ar": "النقاوة والإنبات يُختبران مخبريّاً. إرشاد عامّ.",
    }


