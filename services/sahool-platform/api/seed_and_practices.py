def sowing_depth(seed_size_mm: float, precision: bool = False) -> Dict:
    """عمق البذر المناسب: ~5× حجم البذرة (أو 2× للزراعة الدقيقة)."""
    if seed_size_mm <= 0:
        return {"supported": False, "message_ar": "أدخل حجم بذرة صحيحاً (مم)."}
    factor = 2 if precision else 5
    depth = seed_size_mm * factor
    return {
        "supported": True,
        "seed_size_mm": seed_size_mm,
        "recommended_depth_mm": round(depth, 1),
        "factor": factor,
        "advice_ar": (
            f"ابذر على عمق ~{round(depth, 1)} مم ({factor}× حجم البذرة"
            + (" — زراعة دقيقة)." if precision else ").")
        ),
        "principle_ar": (
            "العمق المثالي ~5× حجم البذرة (2× للزراعة الدقيقة). العميق جدّاً "
            "يعيق الظهور، والضحل جدّاً يجفّف البذرة."
        ),
        "note_ar": "يتأثّر بنوع التربة والرطوبة — التربة الرمليّة تتحمّل عمقاً أكبر قليلاً.",
        "disclaimer_ar": "إرشاد عامّ — راجع توصية المحصول المحدّد.",
    }
