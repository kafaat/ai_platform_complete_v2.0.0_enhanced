def analog_detail(region_keyword: str) -> Dict:
    """تفصيل منطقة مشابهة محدّدة + دروسها."""
    kw = region_keyword.strip()
    for r in _ANALOG_REGIONS:
        if kw in r["region_ar"] or r["region_ar"] in kw or kw in r["country_ar"]:
            return {"supported": True, **r}
    return {
        "supported": False,
        "message_ar": f"لا منطقة «{region_keyword}». المتاح: "
                      + "، ".join(r["region_ar"] for r in _ANALOG_REGIONS),
    }


