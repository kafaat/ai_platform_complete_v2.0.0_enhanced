"""
api/cultural_calendar.py — التقويم الزراعي الثقافي (عرض فقط، خارج محرّك القرار)

اتّفاق صريح ومبدئي: المعرفة المجتمعيّة التجريبيّة (مواعيد زراعة محلّيّة، أصناف
مقاومة) تدخل **محرّك القرار** كقرينة بوزن منخفض (في evidence_corroboration).

أمّا التقويم النجمي/القمري (طوالع النجوم، مراحل القمر مثل سهيل والثريّا) فيُعرَض
هنا **كمعلومة ثقافيّة فقط** — يراها المزارع لاحترام تراثه، لكنّه **لا يدخل أيّ
محرّك قرار ولا يحرّك أيّ توصية**.

السبب (مبدأ الصدق العلمي):
  • لا آليّة سببيّة: موقع النجم لا يؤثّر فيزيائيّاً في التربة/النبات
  • الارتباط الظاهري (إن وُجد) لأنّ التقويم النجمي وكيل للموسم — والموسم نقيسه
    مباشرةً بالحرارة وGDD والمطر (أدقّ وأصدق)
  • إدخاله بوزن منخفض في القرار يمنحه شرعيّة زائفة ويموّه غياب الأساس

لذا: العرض هنا منفصل تماماً. الدالّة لا تُرجِع أيّ "توصية" — فقط سياق ثقافي
موسوم صراحةً بأنّه غير مُستخدَم في القرار.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class CulturalNote:
    """ملاحظة تقويم ثقافي (عرض فقط)."""

    name_ar: str
    period_ar: str
    traditional_practice_ar: str

    def to_dict(self) -> dict:
        return {
            "name_ar": self.name_ar,
            "period_ar": self.period_ar,
            "traditional_practice_ar": self.traditional_practice_ar,
        }


# تقويم نجمي يمني تقليدي (للعرض الثقافي فقط — لا يدخل أيّ قرار)
# مرجع ثقافي عامّ؛ ليس مصدر توصية زراعيّة.
YEMENI_STAR_CALENDAR: list[CulturalNote] = [
    CulturalNote(
        "سهيل", "أواخر الصيف (أغسطس)", "يربطه المزارعون تقليديّاً ببدء اعتدال الحرّ وقرب موسم الزراعة"
    ),
    CulturalNote(
        "الثريّا", "مواقيت متعدّدة عبر السنة", "تُستخدم تقليديّاً لتقدير مواعيد بعض الأعمال الزراعيّة"
    ),
    CulturalNote("مراحل القمر", "شهريّة", "يفضّل بعض المزارعين أعمالاً معيّنة في أطوار قمريّة محدّدة"),
]


def get_cultural_calendar(governorate: str | None = None) -> dict:
    """يُرجع التقويم الثقافي للعرض فقط — مع وسم صريح أنّه خارج محرّك القرار.

    لا يُرجِع أيّ توصية أو وزن أو قرار. سياق ثقافي بحت.
    """
    return {
        "display_only": True,
        "used_in_decision_engine": False,
        "disclaimer_ar": (
            "هذا تقويم ثقافي تراثي يُعرَض احتراماً لخبرة المزارعين، وهو "
            "**لا يدخل** في حساب أيّ توصية زراعيّة. توصيات سهول تُبنى على قياسات "
            "فيزيائيّة (حرارة، GDD، مطر، تربة) لا على مواقع النجوم. لتوقيت الزراعة "
            "بدقّة، اعتمد على تتبّع GDD ودرجات الحرارة."
        ),
        "notes": [n.to_dict() for n in YEMENI_STAR_CALENDAR],
    }
