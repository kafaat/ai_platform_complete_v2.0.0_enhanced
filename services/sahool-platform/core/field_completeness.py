"""core.field_completeness
==========================
درجة اكتمال البيانات لكلّ حقل (per-field DATA-COMPLETENESS).

الهدف: نُظهر للمزارع/المهندس **ما تملكه أبعاد بيانات الحقل وما ينقصها**، ودرجة
مئويّة (0–100) تُعبّر عن مدى توفّر البيانات التي تُمكّن قراراً واثقاً، مع إرشاد
عمليّ صادق لكلّ بُعد ناقص («كيف تُضيفه»).

صدق (HONESTY) — حدّ جوهريّ: هذه الدرجة تقيس **حضور البيانات** (مُمَكِّن للثقة في
القرار)، **لا صحّة المحصول**. حقلٌ كامل البيانات قد يكون مُجهَداً، وحقلٌ سليم قد
تنقصه بيانات. لا نخلط الاثنين — يُوضَّح ذلك في ``note_ar``.

العلاقة بـ``core.data_completeness``: تلك الوحدة تحسب درجة اكتمال موزونة من مجموعة
حقول **حاضرة** (set من الأسماء) وتُنتج رسالة تحفيزيّة + الحقل الأهمّ الناقص. هذه
الوحدة طبقة أعلى **خاصّة بأبعاد بيانات الحقل** التي تخزّنها المنصّة فعليّاً
(هندسة/إحداثيّات/تحليل تربة مخبريّ/NDVI/موسم نشط/تاريخ بذار/رطوبة تربة) — تُحوّل
قاموس إشارات حضور/غياب مسطّحاً إلى درجة + مستوى + إرشاد. حيث تتقاطع الأبعاد مع
``FIELD_WEIGHTS`` نُبقي الفلسفة نفسها (موزون، شفّاف، يُحفّز لا يحجب)، ونُسند المنطق
المنخفض المستوى (مجموع الأوزان ⇒ درجة) إلى نمطها — انظر ``_DIMENSIONS`` أدناه.

نقاء: لا I/O ولا DB. المُدخل قاموس إشارات مسطّح (booleans/قيم)، والمخرج قاموس JSON
صرف. يُجمّع موجِّه ``api/routers/field_completeness.py`` هذا القاموس من القاعدة ثمّ
يستدعي ``score_field_completeness``.
"""

from __future__ import annotations

# ── عقد التهديف (scoring contract) ───────────────────────────────────────────
# كلّ بُعد: (مفتاح الإشارة، الوزن، التسمية العربيّة، لماذا يهمّ، كيف تُضيفه).
# الأوزان مجموعها 100. مرتّبة: حاكمة (تفتح الدقّة) أوّلاً وزناً، ثمّ إثرائيّة.
# مُتوائمة مع فلسفة core.data_completeness.FIELD_WEIGHTS (موزون + يُحفّز لا يحجب)،
# لكنّ مفاتيحها هي أبعاد بيانات الحقل التي تخزّنها المنصّة (لا الحقول المختبريّة
# المجرّدة S3/S4/I3) — لذا نُعرّفها هنا صراحةً بدل إعادة استخدام تلك الأوزان حرفيّاً.
_DIMENSIONS: tuple[tuple[str, int, str, str, str], ...] = (
    # ── أساسيّة (هويّة الحقل المكانيّة) ──
    (
        "has_geometry",
        20,
        "هندسة الحقل (الحدود)",
        "الحدود تُحدّد المساحة وتُمكّن الخرائط وصور الأقمار والمناطق الإداريّة.",
        "ارسم حدود الحقل على الخريطة أو استورد ملفّ GeoJSON/KML/نقاط GPS.",
    ),
    (
        "has_coords",
        10,
        "موقع الحقل (إحداثيّات)",
        "الإحداثيّات (lat/lon) شرطٌ لجلب الطقس وحساب الريّ والمخاطر المناخيّة.",
        "حدّد موقع الحقل على الخريطة — يُشتقّ المركز آليّاً من الحدود المرسومة.",
    ),
    # ── حاكمة (تفتح دقّة القرار) ──
    (
        "has_soil_lab",
        25,
        "تحليل تربة مخبريّ",
        "قيم التربة (pH/EC/المغذّيات) تفتح التسميد الدقيق وإدارة الملوحة بدل التقريب.",
        "ارفع نتيجة تحليل تربة مخبريّ معتمَد (soil_lab_tests) لهذا الحقل.",
    ),
    (
        "has_active_season",
        20,
        "موسم زراعيّ نشط",
        "الموسم النشط يربط المحصول والمراحل بالحقل ويُفعّل التقويم والتوصيات الطوريّة.",
        "فعّل موسماً نشطاً للحقل وحدّد محصوله ونوع الريّ.",
    ),
    # ── إثرائيّة (تزيد قوّة القرار) ──
    (
        "has_sowing_date",
        10,
        "تاريخ البذار",
        "تاريخ البذار يُمكّن حساب GDD وعمر المحصول والمرحلة الفينولوجيّة الدقيقة.",
        "أدخِل تاريخ البذار (sowing_date) في الموسم النشط.",
    ),
    (
        "has_ndvi",
        10,
        "مؤشّر NDVI (استشعار عن بُعد)",
        "متوسّط NDVI من صور القمر قرينةُ نشاطٍ خضريّ تُعزّز ثقة القرار وتكشف التباين.",
        "فعّل أتمتة الصور (Sentinel) لهذا الحقل ليُحسَب متوسّط NDVI تلقائيّاً.",
    ),
    (
        "has_soil_moisture",
        5,
        "رطوبة التربة (تليمتري)",
        "قراءة رطوبة حيّة من أجهزة الحقل تُحسّن دقّة جدولة الريّ وإلحاحه.",
        "اربط جهاز استشعار رطوبة تربة بالحقل ليُرسل قراءات telemetry.",
    ),
)

# مجموع الأوزان — يُحسَب لا يُلصَق (يبقى متّسقاً لو عُدّلت الأبعاد). يجب أن يساوي 100.
_TOTAL_WEIGHT = sum(d[1] for d in _DIMENSIONS)

# حدود المستويات (level cutoffs) على score_pct:
#   rich     ⩾ 80  — البيانات الحاكمة + الأساسيّة متوفّرة ⇒ قرار واثق.
#   moderate ⩾ 45  — أساس جيّد، تنقص أبعاد حاكمة/إثرائيّة ⇒ توصيات تقريبيّة.
#   sparse   <  45  — بيانات شحيحة ⇒ توصيات عامّة فقط حتى يُكمل المزارع.
_LEVEL_RICH_MIN = 80
_LEVEL_MODERATE_MIN = 45

_NOTE_AR = (
    "هذه الدرجة تقيس **حضور بيانات الحقل** (مُمَكِّن لثقة القرار) لا صحّة المحصول. "
    "حقلٌ مكتمل البيانات قد يكون مُجهَداً، وحقلٌ سليم قد تنقصه بيانات — لا نخلط "
    "الاثنين. كلّما اكتملت الأبعاد، زادت دقّة التوصيات وقيمتها."
)


def _truthy(signals: dict, key: str) -> bool:
    """هل الإشارة حاضرة فعلاً؟ يتسامح مع booleans/قيم/None/فوضى (لا استثناء).

    تُعدّ الإشارة «حاضرة» إن كانت قيمتها صادقة (truthy) — بما يشمل أرقاماً
    غير صفريّة ونصوصاً غير فارغة وقواميس/قوائم غير فارغة. None/False/0/""/[]/
    {} كلّها «غائبة». مدخل غير قاموس يُعامَل ككلّ-غائب عبر .get الآمن.
    """
    try:
        return bool(signals.get(key))
    except AttributeError:
        return False


def score_field_completeness(signals: dict) -> dict:
    """يحسب درجة اكتمال بيانات الحقل من قاموس إشارات حضور مسطّح.

    المُدخل ``signals``: قاموس مسطّح بمفاتيح أبعاد البيانات (انظر ``_DIMENSIONS``):
    ``has_geometry``، ``has_coords``، ``has_soil_lab``، ``has_active_season``،
    ``has_sowing_date``، ``has_ndvi``، ``has_soil_moisture`` — قيمها booleans
    (أو أيّ قيمة truthy/falsy). مفاتيح غائبة تُعامَل «غائبة». مدخل فارغ/فوضى ⇒
    درجة منخفضة/صفر بصدق دون استثناء.

    المخرج (JSON صرف):
      - ``score_pct`` (0–100): مجموع أوزان الأبعاد الحاضرة، منسوب إلى 100.
      - ``level``: "rich" | "moderate" | "sparse" (حسب الحدود الموثّقة أعلاه).
      - ``present``: أسماء الأبعاد الحاضرة (مفاتيح ``_DIMENSIONS``).
      - ``missing``: أسماء الأبعاد الناقصة.
      - ``improvements_ar``: لكلّ بُعد ناقص {dimension, why_ar, how_ar} — إرشاد
        عمليّ «كيف تُضيفه» (مرتّب بالوزن تنازليّاً: الأهمّ أوّلاً).
      - ``note_ar``: توضيح الصدق (الدرجة = حضور بيانات لا صحّة محصول).
    """
    present: list[str] = []
    missing: list[str] = []
    raw_score = 0
    improvements: list[dict] = []

    for key, weight, label_ar, why_ar, how_ar in _DIMENSIONS:
        if _truthy(signals, key):
            present.append(key)
            raw_score += weight
        else:
            missing.append(key)
            improvements.append(
                {
                    "dimension": key,
                    "label_ar": label_ar,
                    "weight": weight,
                    "why_ar": why_ar,
                    "how_ar": how_ar,
                }
            )

    # نسبة مئويّة (الأوزان مجموعها 100 أصلاً، لكن نقسم على المجموع المحسوب صراحةً
    # كي تبقى الدرجة 0–100 حتى لو عُدّلت الأبعاد مستقبلاً).
    score_pct = round(100 * raw_score / _TOTAL_WEIGHT) if _TOTAL_WEIGHT else 0

    if score_pct >= _LEVEL_RICH_MIN:
        level = "rich"
    elif score_pct >= _LEVEL_MODERATE_MIN:
        level = "moderate"
    else:
        level = "sparse"

    # الأهمّ أوّلاً: رتّب إرشادات التحسين بالوزن تنازليّاً (أكبر أثرٍ على الدرجة).
    improvements.sort(key=lambda d: -d["weight"])

    return {
        "score_pct": score_pct,
        "level": level,
        "present": present,
        "missing": missing,
        "improvements_ar": improvements,
        "note_ar": _NOTE_AR,
    }
