# الخطر هنا = EC محلول الريّ النهائيّ (ماء + سماد ذائب) المرتفع يحرق الجذور **فوراً**
# (لا تملّح تراكميّ). 2.0 dS/m عتبة محافِظة للأصناف الحسّاسة (أدبيّات الريّ بالتسميد).
# عامّة (fallback)؛ الدقّة لكلّ محصول لاحقاً عبر حسّاسيّة الصنف. تُطبَّق في
