#!/usr/bin/env bash
# تثبيتُ متصفّح Playwright صامدٌ للتعثّر — **علاجُ APT مُعمَّماً على الخطوة التي أفلتت منه**.
#
# **العطل، مقيساً مرّتين على هذا المستودع:**
#   2026-08-18 · تشغيل 32160054946 — عَلِق **٨٠+ دقيقة** بلا سقف، فحجب PR شجرتُه
#     خضراء بالكامل، بينما نجحت الخطوة نفسها على **الرأس نفسه بالبايت** في التشغيل
#     الشقيق 32160058172 في **٢ د ٥٥ ث**.
#   2026-08-19 · تشغيل 32269598189 — سقطت بـ**`exit code 124`** على `d5fd1ec3`، أي
#     أنّ السقف الذي أُضيف بعد الحادثة الأولى **أطلق**: خمس دقائق إلى فشلٍ مُسمّى بدل
#     تعليقٍ صامت.
#
# **والحادثة الثانية هي حجّة هذا الملفّ.** السقف عمل كما صُمِّم — لكنّه، كما تعلّمنا في
# APT حرفيّاً، **يحوّل الحرق إلى فشل ولا يُنجِح التثبيت**. فما نقص هنا هو ما أُضيف
# هناك: تراجعٌ متزايد، ومرآةٌ بديلة بين المحاولات، مع بقاء كلّ محاولة مسقوفة.
#
# **ولماذا المرآة تخصّ هذه الخطوة أصلاً:** `--with-deps` يستدعي `apt-get` **من جوفه**
# لتثبيت اعتماديّات النظام. فمتّجه التعثّر مشترك، والدالّة مُستخرَجة في
# `apt_mirror_fallback.sh` يشترك فيها الاثنان بدل نسختين تنحرفان.
#
# **وحدٌّ يُعلَن ولا يُموَّه:** الخطوة تجلب من مصدرين — مرآة APT **وCDN متصفّحات
# Playwright**. والمرآة تُبدَّل؛ أمّا الـCDN فلا مرآة بديلة مُعدّة له في هذا المستودع،
# فلا يُدّعى تبديلٌ لا يقع. ما يُقدَّم له هو **إعادةُ المحاولة والسقف** — وهما يعالجان
# التعثّر العابر لا الانقطاع الكامل. (`PLAYWRIGHT_DOWNLOAD_HOST` موجود في الأداة، ولا
# يُضبَط هنا لأنّ اختيار مضيفٍ بديل قرارُ سلسلة إمداد لا تفصيلُ صلابة.)
#
# **ولماذا سكربت لا سطرٌ في YAML** — الدرس نفسه: منطقٌ في `run:` لا يُقاس إلّا بتشغيل
# الوظيفة كاملةً. يُستدعى من `tests_v9/test_resilient_playwright_install.py` بـ`npx`
# مزيّف فيُقاس كلُّ فرعٍ منه.
#
# الاستعمال (من داخل `frontend/`):
#   resilient_playwright_install.sh chromium [متصفّح آخر …]
#
# متغيّرات البيئة:
#   PW_TIMEOUT   سقف كلّ محاولة بالثواني (افتراضيّ 300 — المقيس الطبيعيّ ~١٧٥ث)
#   PW_ATTEMPTS  عدد المحاولات (افتراضيّ 3)
#   PW_BACKOFF   ثواني التراجع الأساسيّة (افتراضيّ 10 ⇒ 10 ثمّ 20 …)
set -uo pipefail

[ $# -gt 0 ] || { echo "::error::resilient_playwright_install: لا متصفّح مطلوب" >&2; exit 2; }

PW_TIMEOUT="${PW_TIMEOUT:-300}"
PW_ATTEMPTS="${PW_ATTEMPTS:-3}"
PW_BACKOFF="${PW_BACKOFF:-10}"

# shellcheck source=scripts/ci/apt_mirror_fallback.sh
. "$(dirname "$0")/apt_mirror_fallback.sh"

i=1
while [ "$i" -le "$PW_ATTEMPTS" ]; do
  if timeout -k 10 "$PW_TIMEOUT" npx playwright install --with-deps "$@"; then
    echo "playwright install نجح في المحاولة $i"
    exit 0
  fi
  echo "playwright install تعثّر/تجمّد (محاولة $i من $PW_ATTEMPTS)"
  if [ "$i" -lt "$PW_ATTEMPTS" ]; then
    # التبديل **قبل** التراجع: النوم على مرآةٍ متعثّرة إنفاقُ وقتٍ على نفس الشرط.
    switch_apt_mirror
    sleep $((PW_BACKOFF * i))
  fi
  i=$((i + 1))
done

echo "::error::playwright install تجاوز مهلته $PW_ATTEMPTS مرّات (بما فيها مرآة APT بديلة؛ ولا مرآة بديلة لـCDN المتصفّحات)" >&2
exit 1
