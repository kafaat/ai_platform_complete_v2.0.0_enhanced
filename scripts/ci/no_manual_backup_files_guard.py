#!/usr/bin/env python3
"""حارس CI: يمنع إيداعَ نسخةٍ احتياطيّةٍ يدويّةٍ في الشجرة المتعقَّبة.

**الحادثةُ التي وُجِد لأجلها (2026-08-26):** ملفّان باسم `main.before_p2` كانا
متعقَّبَين في خدمتين مختلفتين — `services/weather-service/` و`services/sam2-inference/`
— حُذِفا في #948 (`7508702a`). ونسخةٌ يدويّةٌ واحدةٌ حادثة؛ **اثنتان في خدمتين نمط**.

**ولمَ الحذفُ وحدَه لا يكفي:** حذفُ ملفَّين يُغلِق الحادثة ولا يمنع الصنف. ولم يكن
في الشجرة كلِّها ما يرفض إيداعَ ملفٍّ بلاحقةٍ كهذه — لا `.gitignore` (مقيس: لا سطرَ
فيه لـ`bak`/`orig`/`before_`) ولا حارس. فالثالثةُ كانت ستمرّ كما مرّت الأولى.

**والضررُ ليس فوضى ترتيب:** النسخةُ الميّتةُ **تُقرَأ مصدراً**. تدخل جردَ الملفّات
وبصماتِ حزمة الإصدار وأدواتِ المسح، ويجدها من يبحث في الشجرة عن `main` **بلا علامةٍ
تقول إنّها بائتة** — فيقرأ منطقاً مهجوراً ويظنّه قائماً. وهذا أخطرُ من ملفٍّ زائد:
مصدرُ حقيقةٍ ثانٍ يتعارض مع الأوّل صامتاً.

**والنطاقُ ضيّقٌ بالقصد:** لواحقُ **معروفةٌ لأدوات النسخ والدمج** وحدَها
(`.bak` · `.orig` · `.rej` · `.save` · `~` · مقطعُ `.before_*`/`.before-*`). ولا
يُلاحَق `.old` ولا `copy`: كلاهما يظهر في أسماءٍ مشروعة، وحارسٌ يُنذِر كذباً
يُدرَّب الناسُ على تجاهله فيموت. مقيسٌ على الشجرة قبل الإضافة: **صفرُ مطابقات**.

يعدّ الملفّات عبر `git ls-files` (المتعقَّبة فقط). **ولا قائمةَ استثناءات فيه**:
المطابقةُ على **اسم الملفّ** لا على محتواه، فالحارسُ واختبارُه يذكران اللواحقَ نصّاً
ولا يُطابِقان. واستثناءٌ لا يستثني شيئاً يبيت ويُوهِم أنّ ثمّة نطاقاً مقتطَعاً.
الفشل يطبع كلَّ مسار.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# لواحقُ أدوات النسخ/الدمج/التحرير — بحدود اسم الملفّ لا في أيّ موضع من المسار.
#   `.bak` · `.orig` · `.rej` · `.save`  ⇒ نهايةُ الاسم
#   `~`                                   ⇒ نهايةُ الاسم (محرّرات)
#   `.before_…` · `.before-…`             ⇒ مقطعٌ داخل الاسم (النمطُ المقيس هنا)
_BACKUP_NAME = re.compile(
    r"""
    (?:\.(?:bak|orig|rej|save)$)      # لاحقةٌ صريحة
    | (?:~$)                          # نسخةُ محرّر
    | (?:\.before[_-][^/]*$)          # main.before_p2 وأخواتُه
    """,
    re.VERBOSE,
)


def tracked_files() -> list[str]:
    # `text=True` وحدَه يفكّ الترميزَ **بلغة الآلة** لا بـUTF-8. وتحت `LC_ALL=C`
    # يتشوّه كلُّ مسارٍ غيرِ ASCII في مخرَج `git ls-files` — فحارسُ النظافة نفسُه
    # يصير مصدرَ قراءةٍ فاسدة، ويُبرِّئ ملفّاً أو يُدين آخرَ بحسب لغة المُشغِّل.
    out = subprocess.run(
        ["git", "ls-files"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return [line for line in out.stdout.splitlines() if line]


def is_manual_backup(rel_path: str) -> bool:
    """مجلّدٌ اسمُه `archive.bak/` لا يُدين ما تحته — **والمِرساةُ وحدَها تكفله**.

    كان هنا `rel_path.rsplit("/", 1)[-1]` لعزل اسم الملفّ. وأسقطته طفرةٌ سجّلتُها
    ثمّ **نجت**: كلُّ بدائل النمط مرساةٌ بـ`$`، ونهايةُ المسار هي نهايةُ الاسم —
    فالعزلُ لم يكن يمنع شيئاً. احتياطٌ لا يمنع شيئاً أسوأُ من غيابه: يُقرَأ ضماناً
    ويُسجَّل تغطيةً. أُسقِط، والخاصّيّةُ باقيةٌ ومُختبَرة.
    """
    return bool(_BACKUP_NAME.search(rel_path))


def scan() -> list[str]:
    return sorted(rel for rel in tracked_files() if is_manual_backup(rel))


def discovery_witness() -> dict:
    """يقول ما فُحِص وما استُبعِد ولماذا — لا عدّاداً وحدَه.

    عدّادٌ يقول «فُحِص ٩٠٠ ملفّ» صادقٌ ومُضلِّلٌ معاً: لا يقول أيّها، ولا يكشف
    ملفّاً دخل الشجرة خارج نطاق المسح.
    """
    tracked = tracked_files()
    return {
        "universe_source": "git ls-files (tracked files only)",
        "discovered_count": len(tracked),
        # لا استثناء: المطابقةُ على الاسم، فلا ملفَّ مشروعاً يقع في النطاق.
        "excluded_paths": {},
        "offenders": scan(),
    }


def main() -> int:
    hits = scan()
    if hits:
        print("no_manual_backup_files_guard FAILED — نسخٌ احتياطيّةٌ يدويّةٌ متعقَّبة:")
        for path in hits:
            print(f"  - {path}")
        print(
            "  النسخةُ الميّتةُ تُقرَأ مصدراً وتدخل الجردَ والبصمات. "
            "احذفها (التاريخُ يحفظها) أو أعطِها اسماً يقول ما هي."
        )
        return 1
    print("no_manual_backup_files_guard_ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
