#: **ولمَ النصفُ:** لأنّه أبسطُ قاعدةٍ تشتقُّ الحدَّ من الرقمين القائمين وتقع حتماً
#: بينهما — لا رقمٌ ثالثٌ يُكتَب بيدٍ فينحرف عنهما.
#:
#: **وحدُّ صدقٍ لازم:** هذا يقيس بيات **الاقتران** لا بيات **الزمن**. جولةٌ تبطؤ بلا
#: نموِّ سجلٍّ قطّ — لتبدُّل عدّاء أو نموِّ ملفّات اختبارٍ خارج المكنسة — تمرّ من هنا
#: خضراء. والقياسُ الزمنيُّ الحقيقيّ يبقى فعلاً بشريّاً دوريّاً لا يفرضه هذا الملفّ.
RE_MEASURE_DRIFT_CEILING = MEASURED_MUTATIONS + (MUTATION_WATERMARK - MEASURED_MUTATIONS) // 2


def _declared_mutations() -> int:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    total = 0
    for section in ("mutated", "behavioural"):
        for spec in (registry.get(section) or {}).values():
            if isinstance(spec, dict):
                total += len(spec.get("mutations") or [])
    return total


def _unit_tests_job() -> dict:
    workflow = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
    jobs = workflow.get("jobs") or {}
    job = jobs.get("unit-tests")
    assert job is not None, "وظيفة `unit-tests` اختفت من ci.yml — العقد يشير إلى لا شيء."
    return job


def test_the_unit_tests_ceiling_stays_above_the_slowest_measured_run():
    """**القيمةُ المقرَّرة ليست هنا** — قفلُها الوحيد في ``test_ci_pipeline_settings``.

    أوّلُ صياغةٍ لهذا الملفّ أكّدت ``timeout-minutes == 90`` أيضاً، فصار للحقيقةِ
    الواحدةِ سلطتان. وذلك يمرّ أخضرَ اليوم ويتباعد غداً: يُحدَّث أحدُهما فيُقرَأ
    الآخرُ عقداً قائماً وهو بائت — وهو صنفُ العطل الذي يطارده هذا المستودع نفسه.

    فالمقيسُ هنا **العلاقة** لا القيمة: أيّاً كان المقرَّر، يجب أن يعلو أبطأ قياسٍ
    حقيقيّ. تكذيبُه بخفضِ السقف تحت ``MEASURED_SLOWEST_MINUTES`` يبقى قائماً، ولا
    يُكرَّر الرقمُ المقرَّر — **ولا رقمُ المرساة**: كانت الرسالةُ تنسب القياسَ إلى
    «#882» وقد انتقلت المرساةُ عنه مرّتين، فصار الشاهدُ المذكورُ في نصّ الفشل يسمّي
    غيرَ الذي قِيس. والقرينةُ موضعُها تعليقُ الثابت وحدَه.
    """
    declared = _unit_tests_job().get("timeout-minutes")
    assert isinstance(declared, int), f"`timeout-minutes` = {declared!r} ليس عدداً."
    assert declared > MEASURED_SLOWEST_MINUTES, (
        f"السقف {declared} لا يعلو أبطأ قياسٍ حقيقيّ {MEASURED_SLOWEST_MINUTES} "
        "دقيقة — سقفٌ أضيق من الواقع يصنع فشلاً زائفاً، ويُقرَأ عطلاً في "
        "الاختبارات لا ضيقاً في السقف فيُشخَّص في الاتّجاه الخطأ."
    )


def test_the_sweep_has_not_grown_past_the_point_that_was_measured():
    """المحرّكُ المهيمن مقيس: كلُّ طفرةٍ دورةُ زرعٍ↔pytest↔ردّ على المسار الحرج."""
    declared = _declared_mutations()
    assert declared <= MUTATION_WATERMARK, (
        f"الطفراتُ المُعلَنة {declared} تجاوزت علامةَ الماء {MUTATION_WATERMARK} "
        f"(كانت {MEASURED_MUTATIONS} عند قياسِ {MEASURED_SLOWEST_MINUTES} دقيقة).\n"
        "أعِد قياساً حقيقيّاً لزمن *Unit Tests*، ثمّ إمّا انقل المكنسة إلى وظيفةٍ "
        "مستقلّة **بعد** إضافة اسمها إلى الفحوص المطلوبة في الـRuleset، أو أعِد "
        "تبرير السقف بالرقم الجديد. لا تُحرِّك هذا الثابت حتّى يخضرّ."
    )


def test_the_anchor_is_re_measured_before_the_universe_drifts_half_the_headroom():
    """**البياتُ الصامت هو العطلُ المقيس — لا النموّ.**

    بلغ السجلُّ ٥٠٩ والمرساةُ عند ٤٨١، ولم يحمرّ شيء: العلامةُ وحدَها لا تنطق قبل
    ٥٧٤، فتُترَك المرساةُ تصف كوناً بعيداً عشراتِ الطفرات ويُقرأ زوجُها (الزمن،
    العدد) عقداً قائماً. وهذا يُحمِّر عند نصف الهامش، والعلاجُ المطلوب **أرخصُ** من
    علاج العلامة: قراءةُ توقيتِ *Unit Tests* من آخر جولةٍ حقيقيّة، وتحديثُ الزوج،
    وإعادةُ اشتقاق العلامة بالصيغة القائمة. لا يُحرَّك أيُّ ثابتٍ حتّى يخضرّ.
    """
    declared = _declared_mutations()
    assert declared <= RE_MEASURE_DRIFT_CEILING, (
        f"الطفراتُ المُعلَنة {declared} انجرفت عن النقطة المقيسة {MEASURED_MUTATIONS} "
        f"أكثرَ من نصف الهامش (الحدّ {RE_MEASURE_DRIFT_CEILING}، والعلامة "
        f"{MUTATION_WATERMARK}).\nالزوجُ ({MEASURED_SLOWEST_MINUTES} دقيقة، "
        f"{MEASURED_MUTATIONS} طفرة) صار يصف كوناً غيرَ القائم. اقرأ زمنَ وظيفة "
        "*Unit Tests* من آخر جولةٍ حقيقيّة، وحدّث الزوجَ معاً، ثمّ أعِد اشتقاق "
        "العلامة بالصيغة نفسِها. لا تُحرِّك هذا الحدّ وحدَه."
    )


def test_both_registry_sections_actually_feed_the_measure():
    """**الشاهدُ الموجب — وبدونه يخضرّ السقفان بلا موضوع.**

    السقفان أعلاه تأكيدانِ على **الغياب** (`declared <= X`)، وكلاهما يبقى صادقاً لو
    عاد ``_declared_mutations`` بصفر: يُعاد تسميةُ قسمٍ في السجلّ، أو يتبدّل مفتاحُ
    ``mutations``، فينهار المقياسُ إلى لا شيء **وتبقى البوّابةُ خضراء** — وهي أسوأُ
    من التجاوز، لأنّ التجاوزَ يُرى.

    فيُقاس أنّ القسمين **يُسهمان فعلاً**: تسميةُ أحدِهما بعيداً كانت تُنقِص المقياسَ
    إلى نصفه صامتاً وتُبعد يومَ إعادة القياس بعشرات الطفرات.

    **وهذا ليس افتراضاً — كُذِّب يدويّاً قبل الالتزام:** أُعيدت تسميةُ `behavioural`
    إلى `behavioural_renamed`، فهبط المقياسُ ٥٠٩ ⇒ ٣٣٨ **ومرّ السقفانِ أخضرين**، ولم
    يحمرّ إلّا هذا الاختبار وحدَه.

    **ولمَ لا طفرةٌ مُسجَّلة في `guard_mutation_registry.json`:** المُكذِّبُ الوحيدُ
    لهذه البيانة هو تعديلُ السجلّ نفسِه — **وهو مُدخَلُ عدّاءِ الطفرات ذاتِه**، فزرعُه
    فيه يُفسِد ما يقرؤه العدّاءُ ليعرف ما يزرع. الاستثناءُ بنيويٌّ لا تهاون، والتكذيبُ
    وقع ومُدوَّنٌ أعلاه بأرقامه.
    """
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    per_section = {
        section: sum(
            len(spec.get("mutations") or [])
            for spec in (registry.get(section) or {}).values()
            if isinstance(spec, dict)
        )
        for section in ("mutated", "behavioural")
    }
    for section, count in per_section.items():
        assert count > 0, (
            f"قسمُ `{section}` لا يُسهم بطفرةٍ واحدة في المقياس — أُعيدت تسميتُه أو "
            "تبدّل مفتاحُ `mutations` فيه، والسقفان صارا يحرسان لا شيء."
        )
    assert sum(per_section.values()) == _declared_mutations(), (
        "مجموعُ القسمين لا يساوي ما يقرؤه المقياس — للحقيقة الواحدة قارئان متباعدان."
    )


def test_the_sweep_still_runs_inside_the_job_the_ruleset_actually_requires():
    """نقلُها بلا ضبط القفل يجعلها إرشاديّةً صامتاً — **والقيدُ مقيسٌ لا مُفترَض.**

    القائمةُ المطلوبة في حماية الفرع مُدوَّنةٌ في
    ``test_check_names_survive_the_slice_and_unit_tests_is_a_singleton``: أربعةَ
    عشرَ اسماً حرفيّاً، مقروءةً من سجلّ ``branch_protection_contract_guard`` —
    و**``Unit Tests`` منها**. فوظيفةٌ جديدة باسمٍ جديد ليست فيها، ونقلُ المكنسة
    إليها يُخرِجها من الحجب **بلا أن يحمرّ شيء**.

    و``branch_protection_contract_guard`` نفسه لا يُعدّد الفحوصَ بالاسم (يفرض حلَّ
    المحادثات وحده)، فلا شيءَ في الشجرة يمنع ذلك الخروج. فيبقى التأكيدُ هنا: ما دامت
    المكنسةُ في *Unit Tests* فهي محكومةٌ بما يحكم اسماً **في القائمة فعلاً**.
    """
    steps = _unit_tests_job().get("steps") or []
    runs = [str(s.get("run") or "") for s in steps if isinstance(s, dict)]
    assert any("guard_mutation_guard.py --run" in r for r in runs), (
        "مكنسةُ الطفرات لم تعد خطوةً في *Unit Tests*. إن نُقِلت عمداً فتأكّد أنّ اسم "
        "الوظيفة الجديدة أُضيف إلى الفحوص المطلوبة في الـRuleset، ثمّ حدّث هذا العقد — "
        "وإلّا فقد كفّت عن الحجب بلا أن تحمرّ."
    )
