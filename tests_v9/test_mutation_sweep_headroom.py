#: الهامشُ المتاح (٩٠ − ٣٧٫٢٣ = ٥٢٫٧٧ دقيقة) ÷ كلفةِ الطفرة المتحفّظة نفسِها التي
#: اشتقّت العلامةَ الأولى (~٤٦٫٥ث = ٠٫٧٧٥د، من ٣١ دقيقة ÷ ٤٠ طفرة) ⇒ +٦٨ ⇒ ٥٧٤.
#: والتحفّظ مقصود ومقيسُ المقدار: ٥٠٦ طفرةً × ٠٫٧٧٥ = ٣٩٢ دقيقةً بالكلفة المفترَضة،
#: والجولةُ كلُّها ٣٧٫٢٣ — فالكلفةُ المستعمَلة ~١٠٫٥ أضعافَ الواقعيّة. **ولا تُخفَّض:**
#: أن يحمرّ باكراً أرخص من أن يحمرّ بعد حرقِ تسعين دقيقة.
#:
#: **ومفارقةٌ ظاهرةٌ تُفسَّر ولا تُخبَّأ: الجولةُ صارت أبطأ والعلامةُ ارتفعت**
#: (٥٥٢ ⇒ ٥٧٤). فالصيغةُ تقيس من **النقطة المقيسة**، وقد تحرّكت ٤٨١ ⇒ ٥٠٦: امتُصّت
#: خمسٌ وعشرون طفرةً بكلفةٍ أقلَّ بكثيرٍ من المفترَضة، فبقي هامشٌ لثمانٍ وستّين رغم
#: انكماش الدقائق ثلاثاً. **وهذا يكشف ما هي العلامةُ حقّاً: ليست سقفاً على النموّ، بل
#: مِشعَلُ إعادةِ قياس** — لأنّ العلاجَ الذي يُمليه بلوغُها (أعِد القياس، أعِد
#: الاشتقاق) يُحرِّكها هي نفسَها. **السقفُ الوحيدُ الذي لا يتحرّك تسعون دقيقة.**
MUTATION_WATERMARK = 574

#: **وحدُّ الانجراف: العلامةُ وحدَها كانت تسمح للمرساة أن تبيت في صمت.** وهذا مقيسٌ
#: لا مُتوقَّع — هو ما وقع اليوم بالضبط: نما السجلُّ ٤٨١ ⇒ ٥٠٩ ولم يحمرّ شيء، وبقيت
#: المرساةُ تصف كوناً بعيداً بثمانٍ وعشرين طفرة حتّى قرأها قارئٌ مصادفةً. فتُجعَل
#: البيانةُ حمراء: حين ينجرف الجاري نصفَ الهامش المشتقّ عن النقطة المقيسة، فالزوجُ
#: (الزمن، العدد) لم يعد يصف الكونَ القائم ويجب أن يُعاد قياسُه — **قبل** بلوغ العلامة
#: بكثير، وبعلاجٍ أرخصَ منها (قراءةُ توقيتٍ من CI، لا نقلُ وظيفة).
