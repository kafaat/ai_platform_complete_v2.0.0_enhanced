#: (عند ٥٠٩). والفجوةُ **عند العدد الثابت نفسِه ٦٫٠٤ دقيقة** — من رتبة الفرق بين
#: الأعداد المختلفة. **فهذه الجولاتُ لا تقيس كلفةً حدّيّةً للطفرة**، ولا تُجيز
#: استبدالَ الكلفة المتحفّظة أدناه بواحدةٍ «مشتقّةٍ من الواقع»: كلُّ ما تحُدُّه هو
