-- v233 — WORKER-CLAIM-NOT-PINNED-BY-A-TRANSACTION-01: إجارةُ مطالبةٍ لصندوق الأحداث.
--
-- `OutboxWorker` في `api/event_bus.py` يلفّ الدُّفعةَ كلَّها في معاملةٍ واحدة كي تبقى
-- أقفالُ `FOR UPDATE SKIP LOCKED` محتجَزة حتى الوسم — فيحبس اتّصالاً وأقفالَ صفوفٍ
-- **أثناء نشرٍ على الشبكة**. وعند تباطؤ الوسيط يتعطّل العاملُ ومعه اتّصالُ المسبح.
--
-- والعلاجُ ليس إطالةَ المعاملة ولا تقصيرَها إلى «حالةٍ» وحدَها:
--   • فصلٌ ثلاثيّ: TX-1 إجارةٌ تُثبَّت بـcommit · الشبكةُ خارج كلّ معاملة · TX-2 إنهاءٌ
--     بـCAS على `claim_token`.
--   • **ولمَ رمزٌ ولا تكفي الحالة:** عند انقضاء الإجارة يُعيد عاملٌ ثانٍ المطالبة،
--     فلو كان شرطُ الإنهاء الحالةَ وحدَها لأنهى الأوّلُ (المتأخّر) مطالبةَ الثاني
--     فوسَم صفّاً لم ينشره. الرمزُ يجعل الإنهاء يخصّ صاحبَه وحده.
--
-- والنمطُ نفسُه مُطبَّقٌ ومُثبَتٌ حيّاً في `v228_worker_claim_lease.sql` على
-- `runtime_event_outbox` وأخواتها (أربعون صفّاً: عشرون مُطالَباً مرّتين بالنمط القديم،
-- صفرٌ بالجديد) — **لكنّ `event_outbox` لم يكن ضمنها**، وهو جدولُ هذا العامل.
--
-- **إضافيّةٌ ومتوافقةٌ مع النسخة القديمة:** ثلاثةُ أعمدةٍ قابلةٍ للإفراغ، بلا قيدٍ ولا
-- قيمةٍ افتراضيّة. الشيفرةُ التي لا تعرفها تعمل كما كانت (الأعمدةُ تبقى NULL)، فترتيبُ
-- وصول المهاجرة قبل الشيفرة أو بعدها لا يكسر شيئاً — وهو شرطٌ لازم لأنّ خدمةَ
-- المهاجرات تتبع `main` مباشرةً.

ALTER TABLE event_outbox
  ADD COLUMN IF NOT EXISTS claim_token UUID,
  ADD COLUMN IF NOT EXISTS claimed_by  TEXT,
  ADD COLUMN IF NOT EXISTS lease_until TIMESTAMPTZ;

-- اختيارُ المرشّحين يصفّي بـ`lease_until` في كلّ دورة؛ فهرسٌ جزئيّ على الصفوف القابلة
-- للإرسال وحدَها (الطابور نشطٌ صغير مقابل تاريخٍ مُرسَلٍ كبير).
CREATE INDEX IF NOT EXISTS idx_outbox_claimable
    ON event_outbox (lease_until, created_at)
    WHERE status IN ('pending', 'failed');
