-- الهدف: إغلاق فجوة إعادة تشغيل TOTP (replay). كان التحقّق يقبل الرمز عبر
--   pyotp.TOTP(secret).verify(code, valid_window=1) بلا تسجيل آخر خطوة زمنيّة
--   مقبولة ⇒ رمز صالح يُعاد استخدامه ضمن نافذته (~90 ثانية عبر ٣ خطوات). من
--   يلتقط رمزاً واحداً (تصيّد بوكيل عكسيّ، كتف، اعتراض على قفزة بلا TLS) يُعيد
--   استخدامه. التصلّب القياسيّ (RFC 6238 §5.2): خزّن آخر خطوة مقبولة لكلّ مستخدم
--   وارفض أيّ رمز خطوته ≤ المخزَّنة.
--
-- العمود: mfa_last_totp_step BIGINT (خطوة يونكس = time // 30). NULL = لم يُستخدَم
--   بعد (يُقبَل أوّل رمز). يُحدَّث ذرّيّاً بشرط التقدّم في مسار التحقّق (auth):
--     UPDATE users SET mfa_last_totp_step=$step
--     WHERE id=$id AND (mfa_last_totp_step IS NULL OR mfa_last_totp_step < $step)
--   عدد الصفوف=0 ⇒ إعادة تشغيل/سباق ⇒ يُرفَض (fail-closed، آمن ضدّ التسابق).
--
-- idempotent: ADD COLUMN IF NOT EXISTS. لا يمسّ بيانات قائمة (NULL افتراضاً).
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_last_totp_step BIGINT;

COMMENT ON COLUMN users.mfa_last_totp_step IS
    'v141: آخر خطوة زمنيّة TOTP مقبولة (anti-replay، خطوة = epoch/30). يُرفَض أيّ رمز '
    'خطوته ≤ هذه القيمة؛ NULL = لم يُستخدَم بعد. يُحدَّث ذرّيّاً بشرط التقدّم.';
