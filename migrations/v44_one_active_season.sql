-- الفجوة المسدودة: لا شيء يمنع وجود أكثر من موسم بحالة 'active' لنفس الحقل،
-- فتنشأ مواسم نشطة متعدّدة متناقضة (أيّها «الحالي»؟). نفرض الثابت على مستوى
-- القاعدة عبر فهرس فريد جزئي: حقل واحد ⇒ على الأكثر صفّ واحد status='active'.
-- (الحالات 'planned' و'closed' غير مقيّدة — تتعدّد بحرّيّة.)
-- يكمّل المنطق في create_season (يُغلق الموسم النشط القديم آليّاً قبل الإدراج)،
-- والفهرس هنا هو الضمانة النهائيّة للثابت. idempotent (IF NOT EXISTS).

CREATE UNIQUE INDEX IF NOT EXISTS uq_seasons_one_active
    ON seasons (field_id) WHERE status = 'active';
